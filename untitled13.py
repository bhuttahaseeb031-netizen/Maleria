import os
import glob
import pandas as pd
import matplotlib.pyplot as plt
import cv2
from sklearn.model_selection import train_test_split

# Get all image paths
image_paths = glob.glob('/content/*.png')

# Analyze classes from filenames
# Typically, malaria datasets contain Parasitized (thinF / C33P1thinF / C1_thinF etc.) and Uninfected (C2NThinF / normal)
# Let's inspect the names to label them.
data = []
for path in image_paths:
    filename = os.path.basename(path)
    # Classify based on dataset patterns (e.g., C2NThinF is Uninfected/Normal, while C1_thinF/C33P1thinF are Parasitized)
    if 'C2NThinF' in filename:
        label = 'Uninfected'
    else:
        label = 'Parasitized'
    data.append({'path': path, 'filename': filename, 'label': label})

df = pd.DataFrame(data)

# Display class distribution
print("Class Distribution:")
